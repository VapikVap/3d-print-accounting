"""Разбор G-code и .gcode.3mf из папки слайсера.

Слайсеры API не имеют, поэтому план (граммы, мм, время) берётся из
комментариев в файлах. Поддержаны форматы PrusaSlicer/OrcaSlicer/Bambu Studio/
Creality Print (Orca-основа) и Cura. Сопоставление с заданием — по имени файла.
"""
import os
import re
import time
import zipfile
import xml.etree.ElementTree as ET

EXTS = (".gcode.3mf", ".gcode", ".3mf", ".bgcode")
HEAD_BYTES = 256 * 1024
TAIL_BYTES = 512 * 1024   # у Orca/Prusa итоги стоят перед большим блоком конфига в конце

_NUM = r"([-+]?\d+(?:[.,]\d+)?)"
PATTERNS = {
    "mm": [
        re.compile(r"^;\s*(?:total\s+)?filament used \[mm\]\s*[=:]\s*(.+)$", re.I),
        re.compile(r"^;\s*total filament length \[mm\]\s*[=:]\s*(.+)$", re.I),
    ],
    "g": [
        re.compile(r"^;\s*total filament used \[g\]\s*[=:]\s*(.+)$", re.I),
        re.compile(r"^;\s*total filament weight \[g\]\s*[=:]\s*(.+)$", re.I),
        re.compile(r"^;\s*filament used \[g\]\s*[=:]\s*(.+)$", re.I),
    ],
    "time": [
        re.compile(r"^;\s*estimated printing time(?: \(normal mode\))?\s*[=:]\s*(.+)$", re.I),
        # Bambu: "; model printing time: 52m 10s; total estimated time: 58m 3s"
        re.compile(r"^;.*?total estimated time\s*[=:]\s*(.+)$", re.I),
        re.compile(r"^;\s*model printing time\s*[=:]\s*(.+?)(?:;|$)", re.I),
    ],
    "cura_time": [re.compile(r"^;TIME:\s*(\d+(?:\.\d+)?)\s*$")],
    "cura_m": [re.compile(r"^;Filament used:\s*(.+)$", re.I)],
    "slicer": [re.compile(r"^;\s*generated by\s+(.+?)(?:\s+on\s.*)?$", re.I),
               re.compile(r"^;Generated with\s+(.+)$", re.I),
               re.compile(r"^;FLAVOR:(.+)$")],
}


def _sum_numbers(text):
    """'1234.5, 0.00' -> 1234.5 (сумма по экструдерам)."""
    vals = [float(v.replace(",", ".")) for v in re.findall(r"\d+(?:\.\d+)?", text.split(";")[0])]
    return sum(vals) if vals else None


def parse_duration(text):
    """'1d 2h 3m 4s' | '2h 5m' | '01:02:03' | '3600' -> секунды."""
    text = text.strip()
    m = re.match(r"^(\d+):(\d{1,2}):(\d{1,2})$", text)
    if m:
        h, mi, s = map(int, m.groups())
        return float(h * 3600 + mi * 60 + s)
    total, found = 0.0, False
    for num, unit in re.findall(r"(\d+(?:\.\d+)?)\s*([dhms])", text, re.I):
        found = True
        total += float(num) * {"d": 86400, "h": 3600, "m": 60, "s": 1}[unit.lower()]
    if found:
        return total
    try:
        return float(text)
    except ValueError:
        return None


def parse_gcode_text(text):
    """Достаёт план из текста G-code. Возвращает dict (поля могут быть None)."""
    out = {"filament_mm": None, "filament_g": None, "est_time_s": None, "slicer": None}
    lists = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line.startswith(";"):
            continue
        m = LIST_RE.match(line)
        if m:
            key = {"filament_type": "type", "filament_colour": "colour"}.get(m.group(1).lower())
            if key and key not in lists:
                lists[key] = m.group(2)
        for key, pat in (("g", PER_FIL_G), ("mm", PER_FIL_MM)):
            m = pat.match(line)
            if m and key not in lists:
                lists[key] = m.group(1)
        for key, pats in PATTERNS.items():
            for p in pats:
                m = p.match(line)
                if not m:
                    continue
                val = m.group(1).strip()
                if key == "mm" and out["filament_mm"] is None:
                    out["filament_mm"] = _sum_numbers(val)
                elif key == "g" and out["filament_g"] is None:
                    out["filament_g"] = _sum_numbers(val)
                elif key == "time" and out["est_time_s"] is None:
                    out["est_time_s"] = parse_duration(val)
                elif key == "cura_time" and out["est_time_s"] is None:
                    out["est_time_s"] = float(val)
                elif key == "cura_m" and out["filament_mm"] is None:
                    mm = re.match(r"([\d.]+)\s*m", val)
                    if mm:
                        out["filament_mm"] = float(mm.group(1)) * 1000
                elif key == "slicer" and out["slicer"] is None:
                    out["slicer"] = val
                break
    out["filaments"] = filaments_from_gcode(lists)
    return out


LIST_RE = re.compile(r"^;\s*(filament_type|filament_colour)\s*=\s*(.+)$", re.I)
PER_FIL_G = re.compile(r"^;\s*filament used \[g\]\s*[=:]\s*(.+)$", re.I)
PER_FIL_MM = re.compile(r"^;\s*filament used \[mm\]\s*[=:]\s*(.+)$", re.I)


def _read_head_tail(path):
    size = os.path.getsize(path)
    with open(path, "rb") as f:
        if size <= HEAD_BYTES + TAIL_BYTES:
            data = f.read()
        else:
            head = f.read(HEAD_BYTES)
            f.seek(size - TAIL_BYTES)
            data = head + b"\n" + f.read()
    return data.decode("utf-8", errors="replace")


def parse_3mf(path):
    """Bambu Studio / Orca: Metadata/slice_info.config, иначе комментарии в plate_N.gcode."""
    out = {"filament_mm": None, "filament_g": None, "est_time_s": None, "slicer": None, "plates": []}
    with zipfile.ZipFile(path) as z:
        names = z.namelist()
        if "Metadata/slice_info.config" in names:
            root = ET.fromstring(z.read("Metadata/slice_info.config"))
            for hdr in root.iter("header_item"):
                if hdr.get("key") == "X-BBL-Client-Type" and not out["slicer"]:
                    out["slicer"] = hdr.get("value")
            for plate in root.iter("plate"):
                meta = {m.get("key"): m.get("value") for m in plate.findall("metadata")}
                fils = [{
                    "slot": int(f.get("id") or i + 1),
                    "material": f.get("type") or "",
                    "color_hex": normalize_color(f.get("color")),
                    "planned_g": float(f.get("used_g") or 0),
                    "planned_mm": float(f.get("used_m") or 0) * 1000,
                    "tray_info_idx": f.get("tray_info_idx") or "",
                } for i, f in enumerate(plate.findall("filament"))]
                fil_g = sum(f["planned_g"] for f in fils)
                fil_m = sum(f["planned_mm"] for f in fils)
                p = {
                    "index": int(meta.get("index") or len(out["plates"]) + 1),
                    "est_time_s": float(meta["prediction"]) if meta.get("prediction") else None,
                    "filament_g": float(meta["weight"]) if meta.get("weight") else (fil_g or None),
                    "filament_mm": fil_m if fil_m else None,
                    "filaments": [f for f in fils if f["planned_g"] > 0],
                }
                out["plates"].append(p)
        if not out["plates"]:
            for n in sorted(names):
                if re.match(r"Metadata/plate_\d+\.gcode$", n):
                    info = parse_gcode_text(z.read(n).decode("utf-8", errors="replace"))
                    out["plates"].append({
                        "index": int(re.findall(r"\d+", n)[0]),
                        "est_time_s": info["est_time_s"],
                        "filament_g": info["filament_g"],
                        "filament_mm": info["filament_mm"],
                        "filaments": info["filaments"],
                    })
                    out["slicer"] = out["slicer"] or info["slicer"]
    # Итог по файлу: сумма пластин (в .gcode.3mf обычно одна нарезанная).
    for k in ("est_time_s", "filament_g", "filament_mm"):
        vals = [p[k] for p in out["plates"] if p[k] is not None]
        out[k] = sum(vals) if vals else None
    out["filaments"] = merge_filaments([f for p in out["plates"] for f in p.get("filaments") or []])
    return out


def normalize_color(c):
    """'#FFFFFF', 'FFFFFFFF' (RGBA из отчёта Bambu), '#fff' -> '#FFFFFF'; иначе ''."""
    c = (c or "").strip().lstrip("#").upper()
    if len(c) == 3:
        c = "".join(ch * 2 for ch in c)
    if len(c) == 8:
        c = c[:6]
    return "#" + c if re.fullmatch(r"[0-9A-F]{6}", c) else ""


def merge_filaments(fils):
    """Сложить пластики с одинаковым номером (если пластин несколько)."""
    by = {}
    for f in fils:
        cur = by.setdefault(f["slot"], dict(f, planned_g=0.0, planned_mm=0.0))
        cur["planned_g"] += f.get("planned_g") or 0
        cur["planned_mm"] += f.get("planned_mm") or 0
    return [by[k] for k in sorted(by)]


def _split_list(v):
    return [x.strip() for x in re.split(r"[;,]", v or "") if x.strip()]


def filaments_from_gcode(lists):
    """Пластики из списков G-code (Orca/Prusa/Bambu: значения через ; или ,)."""
    grams = [float(x) for x in _split_list(lists.get("g"))] if lists.get("g") else []
    mm = [float(x) for x in _split_list(lists.get("mm"))] if lists.get("mm") else []
    types = _split_list(lists.get("type"))
    colors = _split_list(lists.get("colour"))
    n = max(len(grams), len(mm))
    out = []
    for i in range(n):
        g = grams[i] if i < len(grams) else None
        if not g and not (i < len(mm) and mm[i]):
            continue
        out.append({"slot": i + 1, "material": types[i] if i < len(types) else "",
                    "color_hex": normalize_color(colors[i]) if i < len(colors) else "",
                    "planned_g": g or 0.0, "planned_mm": mm[i] if i < len(mm) else 0.0, "tray_info_idx": ""})
    return out


def parse_file(path):
    low = path.lower()
    if low.endswith(".3mf"):
        info = parse_3mf(path)
    else:
        info = parse_gcode_text(_read_head_tail(path))
    info["path"] = path
    info["name"] = os.path.basename(path)
    info["mtime"] = os.path.getmtime(path)
    return info


def normalize(name):
    """Имя для сопоставления: без пути, расширений и регистра."""
    name = os.path.basename(name or "").lower().strip()
    for ext in EXTS:
        if name.endswith(ext):
            name = name[: -len(ext)]
            break
    return re.sub(r"[\s_\-.]+", " ", name).strip()


_cache = {}  # path -> (mtime, info)


def scan(folder, max_files=500):
    """Файлы нарезки в папке (рекурсивно), новые первыми."""
    if not folder or not os.path.isdir(folder):
        return []
    found = []
    for root, _dirs, files in os.walk(folder):
        for fn in files:
            if fn.lower().endswith(EXTS):
                found.append(os.path.join(root, fn))
    found.sort(key=lambda p: os.path.getmtime(p), reverse=True)
    result = []
    for p in found[:max_files]:
        mt = os.path.getmtime(p)
        cached = _cache.get(p)
        if cached and cached[0] == mt:
            result.append(cached[1])
            continue
        try:
            info = parse_file(p)
        except Exception as e:  # битый архив и т.п. — показываем, но не падаем
            info = {"path": p, "name": os.path.basename(p), "mtime": mt, "error": str(e),
                    "filament_mm": None, "filament_g": None, "est_time_s": None, "slicer": None,
                    "filaments": []}
        _cache[p] = (mt, info)
        result.append(info)
    return result


def match(folder, job_filename, files=None):
    """Лучший файл нарезки для имени задания: точное совпадение, затем по префиксу.

    Bambu добавляет к имени задания суффиксы вроде '_plate_1', а Moonraker
    отдаёт путь с подпапками — обе формы сводятся к normalize().
    """
    target = normalize(job_filename)
    if not target:
        return None
    files = files if files is not None else scan(folder)
    exact = [f for f in files if normalize(f["name"]) == target]
    if exact:
        return exact[0]
    stripped = re.sub(r"\s+plate\s+\d+$", "", target)
    loose = [f for f in files
             if normalize(f["name"]) in (stripped,)
             or normalize(f["name"]).startswith(target)
             or target.startswith(normalize(f["name"]) + " ")]
    return loose[0] if loose else None


def age_text(ts):
    return time.strftime("%d.%m.%Y %H:%M", time.localtime(ts))
